async function seedBarBook() {
  let client
  try {
    client = new MongoClient(config.dbURL)
    await client.connect()
    console.log('Connected to MongoDB:', config.dbName)
    const db = client.db(config.dbName)
    const collection = db.collection('barBook')

    const existing = await collection.findOne({ slug: 'default' })
    const now = Date.now()
    const doc = {
      ...BAR_BOOK_CONTENT,
      createdAt: now,
      updatedAt: now,
    }

    if (existing) {
      await collection.updateOne(
        { slug: 'default' },
        { $set: { ...BAR_BOOK_CONTENT, updatedAt: now } }
      )
      console.log('barBook: document updated with previous content.')
    } else {
      await collection.insertOne(doc)
      console.log('barBook: collection created and document inserted with previous content.')
    }
    console.log('Done. Bar book content is in the database.')
  } catch (err) {
    console.error('Seed failed:', err.message)
    process.exit(1)
  } finally {
    if (client) await client.close()
  }
}

seedBarBook()
